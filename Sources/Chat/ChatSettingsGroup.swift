import SwiftUI

/// A titled block of chat settings. Tabs replaced the disclosure arrows, so a
/// group no longer hides what it holds.
struct ChatSettingsGroup<Content: View>: View {
    let title: String
    @ViewBuilder var content: Content

    var body: some View {
        VStack(alignment: .leading, spacing: 8) {
            Text(title)
                .font(.system(size: 11, weight: .semibold))
                .foregroundStyle(.secondary)
                .textCase(.uppercase)
                .padding(.leading, 2)
            SettingsRowGroup { content }
        }
    }
}
